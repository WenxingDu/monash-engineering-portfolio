def lookForLM(image, nextWayPoint = None):
    """Function that look for landmark in view of the robot
            if nextWayPoint is None, 
                we are turning, don't need to check collusio

    Args:
        nextWayPoint (_type_, optional): _description_. Defaults to None.
        if it is None:
            we are turning, so no collision checking needed
        else:
            we are going straight, need to check if we are going to hit anything
        
        outputs:
            landmark : List of landmarks for updating position
            isInCollision (bool): true if we are in collision
            collisionPos: List of [x,y] of things that we are going to hit
    """
    COLLISION_DIS = 0.7
    OBS_RADIUS = 0.1
    
    isInCollision = False
    collisionList = [] #list of coordiant that the robot will go into
    landMarkCoord = []
    landmarkPosition,_ = aruco_det.detect_marker_positions(image)
    
    if nextWayPoint != None:
        disToWaypoint = math.sqrt((nextWayPoint[0]-robot.state[0][0])**2 + (nextWayPoint[1]-robot.state[1][0])**2)
        
        if disToWaypoint > COLLISION_DIS: #we won't look beyond 0.2m for collision
            points = generate_line_points(robot.state[0],robot.state[1], (nextWayPoint[0]+robot.state[0])/2,(nextWayPoint[1]+robot.state[1])/2)
        else:
            points = generate_line_points(robot.state[0],robot.state[1], nextWayPoint[0],nextWayPoint[1])
        
        for landmark in landmarkPosition:
            gobalLM = ekf.compute_gobal_marker(landmark)
            obsCircle = Circle(gobalLM[0][0],gobalLM[1][0],OBS_RADIUS,landmark.tag)
            inCollision, collisionPoint = obsCircle.is_in_collision_with_points(points)
            landMarkCoord.append([gobalLM[0][0],gobalLM[1][0]])
            if inCollision:
                collisionList.append([gobalLM[0][0] , gobalLM[1][0]])
                isInCollision = True
    else:
        return landmarkPosition, collisionList, isInCollision,landMarkCoord
    
    return landmarkPosition, collisionList, isInCollision,landMarkCoord
        
  
