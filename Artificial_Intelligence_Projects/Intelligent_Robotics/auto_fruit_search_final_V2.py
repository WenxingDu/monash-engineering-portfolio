def findClosestObs(listOfAllObs):
    #find the closest obs from the robot, and return a point that can avoid this
    #Input: list of all obs that we will be hitting
    #output: next way point that can avoid hitting the closest obs [x,y]
    
    collisionCoord = None
    minDis = 999
    DIS_FROM_OBS = 0.4 #the distance left/right of the obstals the next way point should be
    
    for i in listOfAllObs:
        prepDis =  math.sqrt((robot.state[0][0] - i[0])**2 + (robot.state[1][0] - i[1]) **2)
        if prepDis < minDis:
            minDis = prepDis
            collisionCoord = [i[0],i[1]]
            
    if collisionCoord != None:
        xNew = DIS_FROM_OBS*np.cos(180-robot[2][0]) + collisionCoord[0]
        yNew = DIS_FROM_OBS*np.sin(180-robot[2][0]) + collisionCoord[0]
        
    return xNew,yNew
  

